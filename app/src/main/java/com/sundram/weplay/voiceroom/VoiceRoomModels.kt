package com.sundram.weplay.voiceroom

/** Number of seats rendered on the voice-room stage. */
const val VOICE_ROOM_SEAT_COUNT = 8

/**
 * Topic used for the room's text chat, carried over LiveKit reliable data packets.
 * LiveKit has no built-in chat feature, so chat is a small pub/sub protocol on top
 * of the same WebRTC connection that carries audio.
 */
const val VOICE_CHAT_TOPIC = "weplay.chat"

/** Participant attributes written by [LiveKitVoiceRoomEngine] to describe seat choice. */
const val ATTR_SEAT = "wp_seat"

/** How the room is currently connected to the voice infrastructure. */
enum class RoomConnection {
    /** Nothing has been attempted yet. */
    IDLE,

    /** LiveKit: dialling the SFU. */
    CONNECTING,

    /** LiveKit: connected, audio and chat available. */
    CONNECTED,

    /** LiveKit: link dropped, SDK is recovering it. */
    RECONNECTING,

    /** LiveKit: the SFU is unreachable and won't retry automatically. */
    FAILED,

    /** LiveKit: the connection was closed, either by us or by the server. */
    DISCONNECTED,

    /** Offline preview engine, used when no self-hosted server is configured. */
    SIMULATED,
}

/** One voice participant occupying a seat on the stage. */
data class RoomMemberVo(
    /** Stable key for composition; LiveKit participant identity. */
    val identity: String,
    val name: String,
    /** Seat index 0..[VOICE_ROOM_SEAT_COUNT], or null when the participant is a listener. */
    val seat: Int?,
    val micOn: Boolean,
    val speaking: Boolean,
    val isSelf: Boolean,
    val joinedAtMs: Long,
) {
    val hasSeat: Boolean get() = seat != null && seat in 0 until VOICE_ROOM_SEAT_COUNT
}

/** Room chat line, either typed by a participant or generated by the client. */
data class RoomMessage(
    val id: Long,
    val author: String,
    val body: String,
    val isSelf: Boolean,
    val system: Boolean = false,
)

/** Everything the voice-room screen renders. */
data class VoiceRoomState(
    val roomId: String = "",
    val connection: RoomConnection = RoomConnection.IDLE,
    /** Shown in the header so it is always obvious which transport is in use. */
    val transportLabel: String = "",
    val members: List<RoomMemberVo> = emptyList(),
    val messages: List<RoomMessage> = emptyList(),
    val selfMicOn: Boolean = false,
    val seatCount: Int = VOICE_ROOM_SEAT_COUNT,
    val error: String? = null,
) {
    /** Participants that hold a stage seat, ordered by seat index. */
    val seated: List<RoomMemberVo> =
        members.filter { it.hasSeat }.sortedBy { it.seat }

    val listenerCount: Int get() = members.count { !it.hasSeat }

    /** Seat list of length [seatCount]; a null entry means the seat is open. */
    fun seatAt(index: Int): RoomMemberVo? = seated.firstOrNull { it.seat == index }

    val self: RoomMemberVo? get() = members.firstOrNull { it.isSelf }

    val selfSeat: Int? get() = self?.seat
}
